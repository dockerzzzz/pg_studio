package dev.pgstudio;

import java.sql.*;
import java.util.ArrayList;
import java.util.List;

/** pg_catalog 기반 DDL 생성. */
public final class Ddl {
    private Ddl() {}

    public static String quote(String id) {
        if (id.matches("[a-z_][a-z0-9_]*") && !SqlFormatter.KEYWORDS.contains(id)) return id;
        return "\"" + id.replace("\"", "\"\"") + "\"";
    }

    public static String qualified(String schema, String name) { return quote(schema) + "." + quote(name); }

    public static String table(Connection c, String schema, String table) throws SQLException {
        String reg = qualified(schema, table);
        StringBuilder sb = new StringBuilder("create table ").append(reg).append(" (\n");
        List<String> lines = new ArrayList<>();
        String cols = "select a.attname, format_type(a.atttypid, a.atttypmod), a.attnotnull, "
                + "pg_get_expr(d.adbin, d.adrelid), a.attidentity::text, a.attgenerated::text "
                + "from pg_attribute a left join pg_attrdef d on d.adrelid = a.attrelid and d.adnum = a.attnum "
                + "where a.attrelid = ?::regclass and a.attnum > 0 and not a.attisdropped order by a.attnum";
        try (PreparedStatement ps = c.prepareStatement(cols)) {
            ps.setString(1, reg);
            try (ResultSet rs = ps.executeQuery()) {
                while (rs.next()) {
                    StringBuilder l = new StringBuilder("    ").append(quote(rs.getString(1))).append(' ').append(rs.getString(2));
                    String ident = rs.getString(5), gen = rs.getString(6), def = rs.getString(4);
                    if ("s".equals(gen)) l.append(" generated always as (").append(def).append(") stored");
                    else if ("a".equals(ident)) l.append(" generated always as identity");
                    else if ("d".equals(ident)) l.append(" generated by default as identity");
                    else if (def != null) l.append(" default ").append(def);
                    if (rs.getBoolean(3)) l.append(" not null");
                    lines.add(l.toString());
                }
            }
        }
        String cons = "select conname, pg_get_constraintdef(oid) from pg_constraint where conrelid = ?::regclass "
                + "order by case contype when 'p' then 1 when 'u' then 2 when 'c' then 3 else 4 end, conname";
        try (PreparedStatement ps = c.prepareStatement(cons)) {
            ps.setString(1, reg);
            try (ResultSet rs = ps.executeQuery()) {
                while (rs.next()) lines.add("    constraint " + quote(rs.getString(1)) + " " + rs.getString(2));
            }
        }
        sb.append(String.join(",\n", lines)).append("\n);\n");
        String idx = "select pg_get_indexdef(i.indexrelid) from pg_index i where i.indrelid = ?::regclass "
                + "and not exists (select 1 from pg_constraint k where k.conindid = i.indexrelid) order by 1";
        try (PreparedStatement ps = c.prepareStatement(idx)) {
            ps.setString(1, reg);
            try (ResultSet rs = ps.executeQuery()) {
                while (rs.next()) sb.append('\n').append(rs.getString(1)).append(";");
            }
        }
        String cmt = "select obj_description(?::regclass, 'pg_class')";
        try (PreparedStatement ps = c.prepareStatement(cmt)) {
            ps.setString(1, reg);
            try (ResultSet rs = ps.executeQuery()) {
                if (rs.next() && rs.getString(1) != null)
                    sb.append("\ncomment on table ").append(reg).append(" is '").append(rs.getString(1).replace("'", "''")).append("';");
            }
        }
        return sb.toString();
    }

    public static String view(Connection c, String schema, String name, boolean materialized) throws SQLException {
        String reg = qualified(schema, name);
        try (PreparedStatement ps = c.prepareStatement("select pg_get_viewdef(?::regclass, true)")) {
            ps.setString(1, reg);
            try (ResultSet rs = ps.executeQuery()) {
                rs.next();
                String body = rs.getString(1).trim();
                if (body.endsWith(";")) body = body.substring(0, body.length() - 1);
                return (materialized ? "create materialized view " : "create or replace view ") + reg + " as\n" + body + ";\n";
            }
        }
    }

    public static String function(Connection c, long oid) throws SQLException {
        try (PreparedStatement ps = c.prepareStatement("select pg_get_functiondef(?)")) {
            ps.setLong(1, oid);
            try (ResultSet rs = ps.executeQuery()) { rs.next(); return rs.getString(1) + ";\n"; }
        }
    }

    public static String sequence(Connection c, String schema, String name) throws SQLException {
        String q = "select data_type::text, start_value, min_value, max_value, increment_by, cycle, cache_size "
                + "from pg_sequences where schemaname = ? and sequencename = ?";
        try (PreparedStatement ps = c.prepareStatement(q)) {
            ps.setString(1, schema);
            ps.setString(2, name);
            try (ResultSet rs = ps.executeQuery()) {
                if (!rs.next()) return "-- sequence not found\n";
                return "create sequence " + qualified(schema, name) + "\n    as " + rs.getString(1)
                        + "\n    start with " + rs.getLong(2) + "\n    increment by " + rs.getLong(5)
                        + "\n    minvalue " + rs.getLong(3) + "\n    maxvalue " + rs.getLong(4)
                        + "\n    cache " + rs.getLong(7) + (rs.getBoolean(6) ? "\n    cycle" : "\n    no cycle") + ";\n";
            }
        }
    }
}
